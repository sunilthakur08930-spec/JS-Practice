// ---------------- 1. ARRAY CHECK & BASICS ----------------
// Array.isArray(arr)  -> चेक करता है कि जो वैल्यू दी गई है वो Array है या नहीं (True/False देता है)
// toString()          -> Array को कॉमा (,) लगाकर एक नार्मल String (टेक्स्ट) में बदल देता है
// join(separator)     -> Array के सभी एलिमेंट्स को अपनी मर्ज़ी के सिंबल (जैसे -, |) से जोड़कर String बनाता है

// ---------------- 2. ADD & REMOVE (जोड़ना और हटाना) ----------------
// push(item)          -> Array के सबसे आखिर में नया एलिमेंट जोड़ता है
// pop()               -> Array के सबसे आखिर वाले एलिमेंट को हटा (डिलीट कर) देता है
// unshift(item)       -> Array के सबसे शुरुआत (Index 0) में नया एलिमेंट जोड़ता है
// shift()             -> Array के सबसे पहले एलिमेंट को हटा देता है

// ---------------- 3. CUT, COPY & PASTE (काट-छांट करना) ----------------
// slice(start, end)                    -> Array का एक हिस्सा काटकर कॉपी करता है (Original Array सेफ रहता है)
// splice(start, deleteCount, ...items) -> Array के बीच से कुछ डिलीट करना, रिप्लेस करना या नया जोड़ना (Original बदल जाता है)
// concat(arr2)                         -> दो या दो से ज़्यादा Arrays को मिलाकर एक नया Array बनाता है
// copyWithin(target, start, end)       -> Array के ही किसी हिस्से को कॉपी करके उसी Array में दूसरी जगह ओवरराइट (Overwrite) कर देता है
// fill(value, start, end)              -> Array की जगहों को किसी एक फिक्स वैल्यू से भर देता है (जैसे सबको 0 कर देना)

// ---------------- 4. SEARCHING (ढूंढना) ----------------
// includes(value)     -> चेक करता है कि कोई आइटम Array में मौजूद है या नहीं (True/False)
// indexOf(value)      -> कोई आइटम किस नंबर (Index) पर है, वो बताता है (ना मिले तो -1 देता है)
// lastIndexOf(value)  -> अगर एक ही आइटम कई बार है, तो उसका सबसे आखिरी वाला Index बताता है

// ---------------- 5. ADVANCE SEARCHING (कंडीशन लगाकर ढूंढना) ----------------
// find(callback)      -> कंडीशन मैच करने वाला सबसे पहला एलिमेंट निकाल कर देता है
// findIndex(callback) -> कंडीशन मैच करने वाले सबसे पहले एलिमेंट का Index (पोजीशन) बताता है

// ---------------- 6. LOOPS & TRANSFORMATIONS (लूप और बदलाव) ----------------
// forEach(callback)   -> Array के हर एक एलिमेंट पर बारी-बारी से कोई काम (Loop) करवाता है
// map(callback)       -> हर एलिमेंट के साथ कैलकुलेशन करके एक बिल्कुल नया Array बनाता है (React में बहुत काम आता है)
// filter(callback)    -> दी गई कंडीशन के हिसाब से एलिमेंट्स को छानकर (Filter करके) नया Array बनाता है
// reduce(callback, initialValue) -> पूरे Array को जोड़कर या कैलकुलेट करके एक सिंगल वैल्यू (जैसे Total Price) निकालता है
// reduceRight(...)    -> Reduce की तरह ही काम करता है, बस कैलकुलेशन पीछे (दाएं) से शुरू करता है

// ---------------- 7. SORTING & REVERSING (क्रम में लगाना) ----------------
// sort(compareFn)     -> Array को A-Z, 0-9 या किसी कस्टम तरीके से क्रम (Order) में लगाता है
// reverse()           -> पूरे Array को उल्टा कर देता है (आखिरी एलिमेंट पहला बन जाता है)

// ---------------- 8. FLATTENING (नेस्टेड ऐरे को सीधा करना) ----------------
// flat(depth)         -> Array के अंदर मौजूद Arrays (Nested Array) को खोलकर एक सीधा (Flat) Array बनाता है
// flatMap(callback)   -> Map और Flat दोनों का काम एक साथ करता है (पहले Map करता है, फिर Flat कर देता है)

// ---------------- 9. CHECKING CONDITIONS (शर्तें चेक करना) ----------------
// every(callback)     -> चेक करता है कि क्या Array के **सभी** एलिमेंट्स कंडीशन पास कर रहे हैं (True/False)
// some(callback)      -> चेक करता है कि क्या Array का **कम से कम एक** एलिमेंट कंडीशन पास कर रहा है (True/False)

// ---------------- 10. ITERATORS (एडवांस लूप्स के लिए) ----------------
// keys()              -> Array के सिर्फ Indexes (0, 1, 2...) की लिस्ट देता है
// values()            -> Array की सिर्फ Values की लिस्ट देता है
// entries()           -> Array का [Index, Value] का जोड़ा बनाकर देता है